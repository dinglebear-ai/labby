import {test, expect} from '@playwright/test'
test('sign in, isolate callers, sign out and block protected access', async ({page, browser}) => {
  await page.goto('/gateway')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await expect(page.locator('#identity')).toHaveText('fixture-user')
  const separate = await browser.newContext()
  const stranger = await separate.newPage()
  await stranger.goto('http://127.0.0.1:4198/gateway')
  await expect(stranger).toHaveURL(/\/sign-in$/)
  await separate.close()
  await page.getByRole('button', {name: 'Sign out'}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/gateway')
  await expect(page).toHaveURL(/\/sign-in$/)
})

test('rejects a sign-in POST without CSRF', async ({request}) => {
  const response = await request.post('/sign-in', {form: {credential: 'fixture-only'}})
  expect(response.status()).toBe(403)
})

test('expired gateway session cannot reopen the protected page', async ({page}) => {
  await page.goto('/sign-in')
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await page.reload()
  await expect(page).toHaveURL(/\/sign-in$/)
})

test('inventory refresh handles empty, malformed and revoked access without stale rows', async ({page}) => {
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.goto('/sign-in')
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page.locator('#server-list')).toContainText('fixture-server')
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/empty')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#servers-empty')).toBeVisible()
  await expect(page.locator('#server-list li')).toHaveCount(0)
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/malformed')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#servers-error')).toContainText('unavailable')
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#server-list')).toContainText('fixture-server')
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/forbidden')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/gateway')
  await expect(page).toHaveURL(/\/sign-in$/)
})
