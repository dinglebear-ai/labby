import {test,expect} from '@playwright/test'
import {signIn,readyCatalog,callRealTool,seedRealCalls} from './mcp-support.mjs'

test('real tool execution creates retained activity and usage without database seeding',async({page})=>{
 await readyCatalog()
 const success=await callRealTool('echo',{text:'real activity evidence'})
 expect(JSON.stringify(success)).toContain('real activity evidence')
 const failure=await callRealTool('fail')
 expect(JSON.stringify(failure)).toContain('Deliberate tool error')
 await signIn(page)
 await page.goto('/activity')
 await expect(page.locator('#usage-calls-table tbody')).toContainText('echo')
 await expect(page.locator('#usage-calls-table tbody')).toContainText('fail')
 await expect(page.locator('#usage-calls-table tbody')).toContainText('real-e2e-mcp')
 await seedRealCalls(26)
 await page.locator('#usage-calls-refresh').click()
 await expect(page.locator('#usage-calls-table tbody tr')).toHaveCount(25)
 await expect(page.locator('#usage-calls-next')).toBeEnabled()
 await page.locator('#usage-calls-next').click()
 await expect(page.locator('#usage-calls-table tbody tr').first()).toBeVisible()
 await page.getByLabel('Outcome',{exact:true}).selectOption('ok')
 await expect(page.locator('#usage-calls-table tbody')).toContainText('echo')
 await page.getByLabel('Usage window',{exact:true}).selectOption('1h')
 await expect(page.locator('#usage-calls-error')).toHaveCount(0)
 await page.goto('/usage')
 await expect(page.locator('#usage-summary')).toBeVisible()
 await expect(page.locator('#usage-empty')).toHaveCount(0)
 await expect(page.locator('#usage-error')).toHaveCount(0)
})
