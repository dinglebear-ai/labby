import {test, expect} from '@playwright/test'

test('retained server catalog supports empty, failure, retry and session isolation', async ({page, browser}) => {
  await page.request.post('http://127.0.0.1:4199/fixture/server_catalog/normal')
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.goto('/sign-in')
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/gateway/servers/fixture-server/catalog')
  await expect(page.locator('#catalog-tools')).toContainText('Fetch a document')
  await expect(page.locator('#catalog-resources')).toHaveText('file:///README.md')
  await expect(page.locator('#catalog-prompts')).toHaveText('review')
  await expect(page.locator('#catalog-results')).not.toContainText('do not render')
  const stranger = await browser.newContext()
  const other = await stranger.newPage()
  await other.goto('http://127.0.0.1:4198/gateway/servers/fixture-server/catalog')
  await expect(other).toHaveURL(/\/sign-in$/)
  await stranger.close()
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/server_catalog/malformed')
  await page.getByRole('button', {name: 'Reload catalog'}).click()
  await expect(page.locator('#catalog-error')).toBeVisible()
  await expect(page.locator('#catalog-results')).toHaveCount(0)
  await page.request.post('http://127.0.0.1:4199/fixture/server_catalog/empty')
  await page.getByRole('button', {name: 'Reload catalog'}).click()
  await expect(page.locator('#catalog-tools-empty')).toBeVisible()
  await page.request.post('http://127.0.0.1:4199/fixture/server_catalog/normal')
  await page.getByRole('button', {name: 'Reload catalog'}).click()
  await expect(page.locator('#catalog-tools')).toContainText('fetch')
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await page.getByRole('button', {name: 'Reload catalog'}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
})
