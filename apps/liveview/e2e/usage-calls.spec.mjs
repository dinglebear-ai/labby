import {test, expect} from '@playwright/test'

test('retained call filters and cursor pages recover and protect caller activity', async ({page, browser}) => {
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.request.post('http://127.0.0.1:4199/fixture/usage_calls/normal')
  await page.goto('/activity')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/activity')
  await expect(page.locator('#usage-calls-table tbody')).toContainText('fetch')
  await expect(page.locator('#usage-calls-table tbody')).not.toContainText('private-payload')
  await page.getByRole('button', {name: 'Next page'}).click()
  await expect(page.locator('#usage-calls-table tbody')).toContainText('fetch_html')
  await expect(page.getByRole('button', {name: 'Next page'})).toBeDisabled()
  await page.getByLabel('Usage window').selectOption('1h')
  await expect(page.getByRole('button', {name: 'Next page'})).toBeEnabled()
  await expect(page.locator('#usage-calls-table tbody')).not.toContainText('fetch_html')
  await page.getByLabel('Outcome').selectOption('timeout')
  await expect(page.locator('#usage-calls-table tbody')).toContainText('timeout')
  const stranger = await browser.newContext()
  try {
    const other = await stranger.newPage()
    await other.goto('http://127.0.0.1:4198/activity')
    await expect(other).toHaveURL(/\/sign-in$/)
  } finally { await stranger.close() }
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/usage_calls/malformed')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#usage-calls-error')).toContainText('unavailable')
  await expect(page.locator('#usage-calls-table tbody tr')).toHaveCount(0)
  await page.request.post('http://127.0.0.1:4199/fixture/usage_calls/empty')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#usage-calls-empty')).toBeVisible()
  await page.request.post('http://127.0.0.1:4199/fixture/usage_calls/normal')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#usage-calls-table tbody')).toContainText('fetch')
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/activity')
  await expect(page).toHaveURL(/\/sign-in$/)
})
