import {test, expect} from '@playwright/test'

test('five native Access groups, keyboard dialogs, responsive layout and one-time token custody', async ({page}) => {
  const errors = []
  page.on('pageerror', () => errors.push('browser-error'))
  await page.goto('/sign-in')
  await page.getByLabel('Gateway credential').fill('controlled-access-fixture')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await page.goto('/access')
  for (const card of ['members', 'invitations', 'admins', 'credentials', 'assignments']) {
    await expect(page.locator(`#access-card-${card}`)).toHaveAttribute('data-state', 'loaded')
  }
  await expect(page.getByRole('heading', {name: 'People & teams', exact: true})).toBeVisible()
  await expect(page.locator('#access-card-invitations')).toContainText('No records')
  for (const width of [1440, 740, 320]) {
    await page.setViewportSize({width, height: 1000})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const panel of await page.locator('.ac-main .ac-panel').all()) {
      const box = await panel.boundingBox()
      if (box) {
        expect(box.x >= 0 && box.x + box.width <= width).toBe(true)
      }
    }
    await page.locator('#access-actions summary').focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('#access-actions')).toHaveAttribute('open', '')
    await page.keyboard.press('Escape')
    await expect(page.locator('#access-actions')).not.toHaveAttribute('open', '')
    await expect(page.locator('#access-actions summary')).toBeFocused()
    await page.screenshot({path: `test-results/access/access-${width}-controlled.png`, fullPage: true})
  }
  const open = async action => {
    await page.locator('#access-actions summary').click()
    await page.locator(`#access-action-${action.replaceAll('.', '-')}`).click()
    await expect(page.locator('#access-dialog')).toBeVisible()
  }
  await open('access.team.member.add')
  await page.getByLabel('Existing principal ID').fill('offline-principal')
  await page.locator('#access-confirm').check()
  await page.evaluate(() => window.liveSocket.disconnect())
  await expect(page.locator('#access-submit')).toBeDisabled()
  await page.locator('#access-action-form').evaluate(form => form.requestSubmit())
  await page.evaluate(() => window.liveSocket.connect())
  await expect(page.locator('#access-connection-status')).toBeHidden()
  await expect(page.locator('#access-card-members')).toHaveAttribute('data-state', 'loaded')
  await expect(page.locator('#access-card-members')).not.toContainText('offline-principal')
  await page.goto('/access')
  await expect(page.locator('#access-card-members')).toHaveAttribute('data-state', 'loaded')
  await expect(page.locator('#access-card-members')).not.toContainText('offline-principal')
  await open('access.team.member.add')
  await page.getByLabel('Existing principal ID').fill('keyboard-principal')
  await page.keyboard.press('Escape')
  await expect(page.locator('#access-dialog')).toBeHidden()
  await expect(page.locator('#access-actions summary')).toBeFocused()
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.team.member.add')
  await expect(page.getByLabel('Existing principal ID')).toHaveValue('')
  await page.getByLabel('Existing principal ID').fill('new-principal')
  await page.locator('#access-confirm').check()
  await page.locator('#access-submit').click()
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'reconciled')
  await expect(page.locator('#access-card-members')).toContainText('new-principal')
  // Close the still-open menu before opening another action.
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.team_project.assign')
  await page.getByLabel('Project id', {exact: true}).fill('project')
  await page.getByLabel('Role', {exact: true}).selectOption('viewer')
  await page.locator('#access-confirm').check()
  await page.locator('#access-submit').click()
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'reconciled')
  await expect(page.locator('#access-card-assignments')).toContainText('viewer')
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.team.member.remove')
  await page.getByLabel('Existing principal ID').fill('protected-owner')
  await page.locator('#access-confirm').check()
  await page.locator('#access-submit').click()
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'failed')
  await expect(page.locator('#access-receipt')).toContainText('last owner is protected')
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.gateway_credential.bind')
  await page.getByLabel('Upstream name').fill('fixture-upstream')
  await page.getByLabel('Host credential reference ID').fill('fixture-reference')
  await page.locator('#access-confirm').check()
  await page.locator('#access-submit').click()
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'reconciled')
  await expect(page.locator('#access-card-credentials')).toContainText('fixture-reference')
  await expect(page.locator('#access-card-credentials')).toContainText('Custodian p')
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.gateway_credential.revoke')
  await page.getByLabel('Upstream name').fill('fixture-upstream')
  await page.locator('#access-confirm').check()
  await page.locator('#access-submit').click()
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'reconciled')
  await expect(page.locator('#access-card-credentials')).toContainText('revoked')
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.team_invitation.create')
  await page.getByLabel('Existing principal ID').fill('p')
  await page.getByLabel('Expires after (seconds)').fill('60')
  await page.locator('[data-access-generate]').click()
  expect(await page.locator('#access-field-token').evaluate(input => /^[0-9a-f]{64}$/.test(input.value) && /[1-9a-f]/.test(input.value))).toBe(true)
  expect(await page.locator('#access-field-token').getAttribute('name')).toBeNull()
  expect(await page.locator('#access-field-token').getAttribute('value') === null).toBe(true)
  await page.locator('#access-confirm').check()
  await page.locator('#access-submit').click()
  await expect(page.locator('#access-one-time')).toBeVisible()
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'accepted_observed')
  expect(await page.evaluate(() => {
    const value = document.querySelector('#access-created-secret').value
    return value.length === 64 && !location.href.includes(value) && !Object.values(localStorage).some(v => v.includes(value)) && !Object.values(sessionStorage).some(v => v.includes(value)) && !document.cookie.includes(value) && !document.documentElement.outerHTML.includes(value)
  })).toBe(true)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async () => {throw new Error('controlled clipboard failure')}}}))
  await page.locator('[data-access-copy]').click()
  await expect(page.locator('[data-access-copy-status]')).toContainText('Invitation created. Clipboard access failed.')
  await expect(page.locator('#access-receipt')).toHaveAttribute('data-status', 'accepted_observed')
  await page.locator('[data-access-reveal]').click()
  await expect(page.locator('[data-access-reveal]')).toBeDisabled()
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async () => {}}}))
  await page.locator('[data-access-copy]').click()
  expect(await page.locator('#access-created-secret').inputValue() === '').toBe(true)
  await expect(page.locator('[data-access-copy-status]')).toContainText('Token copied')
  if (await page.locator('#access-actions').getAttribute('open') !== null) await page.locator('#access-actions summary').click()
  await open('access.team_invitation.accept')
  await page.locator('#access-field-token').fill('ab'.repeat(32))
  await page.goto('/access')
  await expect(page.locator('#access-dialog')).toBeHidden()
  expect(await page.locator('#access-created-secret').inputValue() === '').toBe(true)
  expect(errors.length).toBe(0)
})
