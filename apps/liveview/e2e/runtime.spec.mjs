import {test, expect} from '@playwright/test'

test('runtime preserves unavailable values, recovers failed samples and isolates revoked callers', async ({page, browser}) => {
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.request.post('http://127.0.0.1:4199/fixture/runtime/normal')
  await page.goto('/runtime')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/runtime')
  await expect(page.locator('#runtime-cpu')).toHaveText('6.4%')
  await expect(page.locator('#runtime-metrics')).toContainText('340.0 MiB')
  await expect(page.locator('#runtime-metrics')).not.toContainText('not projected')
  const stranger = await browser.newContext()
  try {
    const other = await stranger.newPage()
    await other.goto('http://127.0.0.1:4198/runtime')
    await expect(other).toHaveURL(/\/sign-in$/)
  } finally { await stranger.close() }
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/runtime/malformed')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#runtime-error')).toContainText('unavailable')
  await expect(page.locator('#runtime-metrics')).toHaveCount(0)
  await page.request.post('http://127.0.0.1:4199/fixture/runtime/unsupported')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#runtime-unsupported')).toBeVisible()
  await expect(page.locator('#runtime-cpu')).toHaveText('Unavailable')
  await page.request.post('http://127.0.0.1:4199/fixture/runtime/normal')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#runtime-cpu')).toHaveText('6.4%')
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/runtime')
  await expect(page).toHaveURL(/\/sign-in$/)
})
