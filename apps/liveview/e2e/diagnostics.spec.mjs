import {test, expect} from '@playwright/test'

test('diagnostics refresh recovers and revoked access removes protected findings', async ({page, browser}) => {
  await page.request.post('http://127.0.0.1:4199/fixture/diagnostics/normal')
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.goto('/diagnostics')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/diagnostics')
  await expect(page.locator('#diagnostics-findings')).toContainText('Disk space is low')
  await expect(page.locator('#diagnostics-findings')).toContainText('Warning')
  const stranger = await browser.newContext()
  try {
    const other = await stranger.newPage()
    await other.goto('http://127.0.0.1:4198/diagnostics')
    await expect(other).toHaveURL(/\/sign-in$/)
  } finally {
    await stranger.close()
  }
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/diagnostics/malformed')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#diagnostics-error')).toContainText('unavailable')
  await expect(page.locator('#diagnostics-findings li')).toHaveCount(0)
  await page.request.post('http://127.0.0.1:4199/fixture/diagnostics/empty')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#diagnostics-empty')).toBeVisible()
  await page.request.post('http://127.0.0.1:4199/fixture/diagnostics/normal')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#diagnostics-findings')).toContainText('Disk space is low')
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/diagnostics')
  await expect(page).toHaveURL(/\/sign-in$/)
})
