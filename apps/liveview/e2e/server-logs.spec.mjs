import {test, expect} from '@playwright/test'

test('server logs poll, pause, filter, recover and preserve caller isolation', async ({page, browser}) => {
  const mode = value => page.request.post(`http://127.0.0.1:4199/fixture/server_logs/${value}`)
  await mode('long')
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.goto('/logs')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/logs')
  const lines = page.locator('#server-log-lines')
  await expect(lines).toContainText('<script>boom</script>')
  await expect(lines.locator('script')).toHaveCount(0)
  await expect(lines).not.toContainText('private-token')
  await expect(page.getByRole('button', {name: 'Pause', exact: true})).toBeVisible()
  await expect(lines).toHaveAttribute('data-following', 'true')
  await expect.poll(() => lines.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  await expect.poll(() => lines.evaluate(el => el.scrollHeight - el.scrollTop <= el.clientHeight + 1)).toBe(true)
  const stranger = await browser.newContext()
  try {
    const other = await stranger.newPage()
    await other.goto('http://127.0.0.1:4198/logs')
    await expect(other).toHaveURL(/\/sign-in$/)
  } finally { await stranger.close() }
  await page.getByRole('button', {name: 'Pause', exact: true}).click()
  await expect(lines).toHaveAttribute('data-following', 'false')
  await lines.evaluate(el => { el.scrollTop = 0 })
  await mode('malformed')
  // A paused viewer must retain its snapshot through an entire poll interval.
  await page.waitForTimeout(2300)
  await expect(page.locator('#logs-error')).toHaveCount(0)
  await expect(lines).toContainText('boom')
  expect(await lines.evaluate(el => el.scrollTop)).toBe(0)
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#logs-error')).toBeVisible()
  await expect(lines.locator('.console-log-line')).toHaveCount(0)
  await mode('empty')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#logs-empty')).toBeVisible()
  await mode('normal')
  await page.getByLabel('Search logs').fill('boom')
  await page.getByLabel('Level', {exact: true}).selectOption('ERROR')
  await page.getByRole('button', {name: 'Apply filters', exact: true}).click()
  await expect(lines).toContainText('boom')
  await page.getByRole('button', {name: 'Follow', exact: true}).click()
  await expect(lines).toHaveAttribute('data-following', 'true')
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await expect(page).toHaveURL(/\/sign-in$/, {timeout: 10000})
})
