import {test, expect} from '@playwright/test'

test.use({screenshot: 'off', trace: 'off', video: 'off'})

test('Gateway disclosures retain independent native state and focus across draft patches', async ({page}) => {
  page.setDefaultTimeout(10000)
  await page.goto('/gateway')
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await page.locator('[data-phx-session].phx-connected').waitFor()
  await page.locator('#gateway-add').click()
  const authentication = page.locator('details.gm-section').filter({has: page.locator('#gm-bearer-env')})
  const headers = page.locator('details.gm-private-map').filter({has: page.locator('#gm-headers-intent')})
  const environment = page.locator('details.gm-private-map').filter({has: page.locator('#gm-env-intent')})
  const exposure = page.locator('details.gm-section').filter({has: page.locator('#gm-expose_tools')})
  await authentication.locator('summary').first().focus()
  await page.keyboard.press('Enter')
  await headers.locator('summary').focus()
  await page.keyboard.press('Space')
  await page.locator('#gm-headers-intent').selectOption('replace')
  await expect(page.locator('#gm-headers')).toBeVisible()
  await expect(authentication).toHaveAttribute('open', '')
  await expect(headers).toHaveAttribute('open', '')
  await expect(environment).not.toHaveAttribute('open', '')
  await expect(exposure).not.toHaveAttribute('open', '')
  await page.locator('#gm-headers').fill('{"x-fixture":"draft"}')
  await expect(page.locator('#gm-server-form')).not.toHaveClass(/phx-change-loading/)
  await expect(page.locator('#gm-headers')).toBeFocused()
  await expect(page.locator('#gm-headers')).toHaveValue('{"x-fixture":"draft"}')
  await page.locator('#gm-name').fill('draft-patch')
  await expect(page.locator('#gm-server-form')).not.toHaveClass(/phx-change-loading/)
  await expect(page.locator('#gm-name')).toBeFocused()
  await expect(page.locator('#gm-headers')).toBeVisible()
  await headers.locator('summary').focus()
  await page.keyboard.press('Enter')
  await page.locator('#gm-url').fill('https://fixture.invalid/mcp')
  await expect(page.locator('#gm-server-form')).not.toHaveClass(/phx-change-loading/)
  await expect(headers).not.toHaveAttribute('open', '')
  await expect(authentication).toHaveAttribute('open', '')
  await exposure.locator('summary').focus()
  await page.keyboard.press('Enter')
  await page.locator('#gm-expose_tools').fill('["echo"]')
  await expect(page.locator('#gm-server-form')).not.toHaveClass(/phx-change-loading/)
  await expect(exposure).toHaveAttribute('open', '')
  await expect(authentication).toHaveAttribute('open', '')
  await expect(headers).not.toHaveAttribute('open', '')
  await authentication.locator('summary').first().focus()
  await page.keyboard.press('Enter')
  await page.locator('#gm-name').fill('another-patch')
  await expect(page.locator('#gm-server-form')).not.toHaveClass(/phx-change-loading/)
  await expect(authentication).not.toHaveAttribute('open', '')
  await expect(exposure).toHaveAttribute('open', '')
  await page.locator('#gm-close').click()
  await page.locator('#gateway-add').click()
  await expect(authentication).not.toHaveAttribute('open', '')
  await expect(exposure).not.toHaveAttribute('open', '')
})
