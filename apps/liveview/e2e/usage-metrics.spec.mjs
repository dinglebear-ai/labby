import {test, expect} from '@playwright/test'

const fixture = 'http://127.0.0.1:4199'
const mode = (page, value) => page.request.post(`${fixture}/fixture/usage_metrics/${value}`)

test('exact usage windows, recovery, private fields, isolation and expiry', async ({page, browser}) => {
  await mode(page, 'normal')
  await page.goto('/sign-in')
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/usage')
  await expect(page.locator('#usage-summary')).toContainText('8')
  await expect(page.locator('#usage-metrics')).not.toContainText('do-not-display')
  await expect(page.locator('#usage-latency')).toContainText('125.5 ms')
  await page.getByLabel('Usage window').selectOption('1h')
  await expect(page.locator('#usage-content')).toBeVisible()
  await expect(page.getByLabel('Usage window')).toHaveValue('1h')
  await page.getByLabel('Usage window').selectOption('7d')
  await expect(page.locator('#usage-content')).toBeVisible()
  await expect(page.getByLabel('Usage window')).toHaveValue('7d')
  const context = await browser.newContext()
  const stranger = await context.newPage()
  await stranger.goto('http://127.0.0.1:4198/usage')
  await expect(stranger).toHaveURL(/\/sign-in$/)
  await context.close()
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  for (const failure of ['malformed', 'oversized', 'unavailable']) {
    await mode(page, failure)
    await page.getByRole('button', {name: 'Refresh usage', exact: true}).click()
    await expect(page.locator('#usage-error')).toBeVisible()
    await expect(page.locator('#usage-content')).toHaveCount(0)
    await mode(page, 'normal')
    await page.getByRole('button', {name: 'Refresh usage', exact: true}).click()
    await expect(page.locator('#usage-content')).toBeVisible()
  }
  await mode(page, 'empty')
  await page.getByRole('button', {name: 'Refresh usage', exact: true}).click()
  await expect(page.locator('#usage-empty')).toBeVisible()
  await mode(page, 'unauthorized')
  await page.getByRole('button', {name: 'Refresh usage', exact: true}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/usage')
  await expect(page).toHaveURL(/\/sign-in$/)
  await mode(page, 'normal')
})
