import {test, expect} from '@playwright/test'

test('observed clients retain history semantics, recover and isolate protected data', async ({page, browser}) => {
  await page.request.post('http://127.0.0.1:4199/fixture/clients/normal')
  await page.request.post('http://127.0.0.1:4199/fixture/inventory/normal')
  await page.goto('/clients')
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.getByLabel('Gateway credential').fill('fixture-only')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(/\/gateway$/)
  await page.goto('/clients')
  await expect(page.locator('#clients-list')).toContainText('Codex')
  await expect(page.locator('#clients-list')).toContainText('42 observations')
  await expect(page.getByText('Observation history, not connection liveness or a count of unique people.')).toBeVisible()
  await expect(page.locator('#clients-list')).not.toContainText('not projected')
  const stranger = await browser.newContext()
  try {
    const other = await stranger.newPage()
    await other.goto('http://127.0.0.1:4198/clients')
    await expect(other).toHaveURL(/\/sign-in$/)
  } finally { await stranger.close() }
  await page.setViewportSize({width: 320, height: 800})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.request.post('http://127.0.0.1:4199/fixture/clients/malformed')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#clients-error')).toContainText('unavailable')
  await expect(page.locator('#clients-list li')).toHaveCount(0)
  await page.request.post('http://127.0.0.1:4199/fixture/clients/empty')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#clients-empty')).toBeVisible()
  await page.request.post('http://127.0.0.1:4199/fixture/clients/normal')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page.locator('#clients-list')).toContainText('Codex')
  await page.request.post('http://127.0.0.1:4199/fixture/expire')
  await page.getByRole('button', {name: 'Refresh', exact: true}).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  await page.goto('/clients')
  await expect(page).toHaveURL(/\/sign-in$/)
})
